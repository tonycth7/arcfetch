/// Retrieve an animated keyframe slice for `name` at a given `tick`.
/// Falls back to the static logo when a logo has only 1 frame.
pub fn from_name_frame(name: &str, tick: usize) -> &'static [&'static str] {
    match name.trim().to_ascii_lowercase().as_str() {
        "atom" => FRAMES_ATOM[tick % FRAMES_ATOM.len()],
        "dna" => FRAMES_DNA[tick % FRAMES_DNA.len()],
        "arcreactor" | "arc" | "arc_reactor" => {
            FRAMES_ARCREACTOR[tick % FRAMES_ARCREACTOR.len()]
        }
        _ => from_name(name),
    }
}

